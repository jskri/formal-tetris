Lemma InitCorrect : ∀ (bags : ℕ → ℕ → T1.Piece) (H : ∀ i, T4.PieceSet (bags i)),
  Correct (Init bags H).
Proof.
  intros bags H; unfold Correct, Init; apply T5P.InitCorrect.
Qed.

Lemma NextCorrect : ∀ [e : Event] [s s' : State]
  (Hc : Correct s)
  (Hn : Next e s = Some s'),
  Correct s'.
Proof.
  intros e s s' Hc Hn.
  unfold Correct in *.
  destruct e as [e5 | cw].
  - (* forwarded T5 event *)
    unfold Next, NextT5Event in Hn.
    eapp T5P.NextCorrect.
  - (* RotateKick: guard, then whichever shift succeeded (left, else right) *)
    unfold Next, RotateKickPiece in Hn; cbv zeta in Hn.
    destruct (! T5.gameover s &&
              ! match T5.RotatePiece cw s with Some _ => true | None => false end)
      eqn: Eg; [ | discriminate Hn ].
    destruct (T5.RotatePiece cw (T5.NewPieceYXState (T5.py s, T5.px s - 1) s))
      as [r |] eqn: El.
    + (* left succeeded: Hn collapses to Some r = Some s' *)
      assert (Er : r = s') by (inject Hn; auto).
      rewrite Er in El.
      eapp RotateKickBranchCorrect.
    + (* left failed: Hn collapses to the right-shift call directly *)
      eapp RotateKickBranchCorrect.
Qed.

Lemma RotateKickPieceCorrectWithoutGameover : ∀ [s s' cw]
  (Hc : CorrectWithoutGameover s)
  (Hn : RotateKickPiece cw s = Some s'),
  CorrectWithoutGameover s'.
Proof.
  intros.
  unfold RotateKickPiece in Hn; cbv zeta in Hn.
  destruct (! T5.gameover s &&
            ! match T5.RotatePiece cw s with Some _ => true | None => false end)
    eqn: Eg; [ | discriminate Hn ].
  destruct (T5.RotatePiece cw (T5.NewPieceYXState (T5.py s, T5.px s - 1) s))
    as [r |] eqn: El.
  - assert (Er : r = s') by (inject Hn; auto).
    rewrite Er in El.
    assert (Hres : T5.CorrectWithoutGameover s' ∧ T5.mg s' = T5.mg s ∧ T5.gameover s' = T5.gameover s)
      by (eapply RotateKickBranchCorrectWithoutGameover; eassumption).
    exact (proj1 Hres).
  - assert (Hres : T5.CorrectWithoutGameover s' ∧ T5.mg s' = T5.mg s ∧ T5.gameover s' = T5.gameover s)
      by (eapply RotateKickBranchCorrectWithoutGameover; eassumption).
    exact (proj1 Hres).
Qed.

Lemma RotateKickPieceMgGameoverUnchanged : ∀ [s s' cw]
  (Hc : CorrectWithoutGameover s)
  (Hn : RotateKickPiece cw s = Some s'),
  mg s' = mg s ∧ gameover s' = gameover s.
Proof.
  intros.
  unfold RotateKickPiece in Hn; cbv zeta in Hn.
  destruct (! T5.gameover s &&
            ! match T5.RotatePiece cw s with Some _ => true | None => false end)
    eqn: Eg; [ | discriminate Hn ].
  destruct (T5.RotatePiece cw (T5.NewPieceYXState (T5.py s, T5.px s - 1) s))
    as [r |] eqn: El.
  - assert (Er : r = s') by (inject Hn; auto).
    rewrite Er in El.
    assert (Hres : T5.CorrectWithoutGameover s' ∧ T5.mg s' = T5.mg s ∧ T5.gameover s' = T5.gameover s)
      by (eapply RotateKickBranchCorrectWithoutGameover; eassumption).
    exact (proj2 Hres).
  - assert (Hres : T5.CorrectWithoutGameover s' ∧ T5.mg s' = T5.mg s ∧ T5.gameover s' = T5.gameover s)
      by (eapply RotateKickBranchCorrectWithoutGameover; eassumption).
    exact (proj2 Hres).
Qed.

Theorem SpecCorrect : ∀ e s s',
    (∀ bags H, Correct (Init bags H))
  ∧ (Correct s → Next e s = Some s' → Correct s').
Proof. split; eauto using InitCorrect, NextCorrect. Qed.


