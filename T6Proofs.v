Theorem CorrectStepHolds : ∀ s s'
  (Hc : Correct s),
  CorrectStep s s'.
Proof.
  intros.
  set (s3 := T4.s3 (T5.s4 (s5 s))).
  set (s3' := T4.s3 (T5.s4 (s5 s'))).
  set (s2 := T3.s2 s3).
  set (s2' := T3.s2 s3').
  enough (T2.NonDecreasingScore s2 s2' ∧ T2.NonDecreasingLevel s2 s2' ∧
      T2.ScoreRisesOnClear s2 s2' ∧ T3.HoldMonotone s3 s3')
    by now unfold CorrectStep, T5.CorrectStep, T4.CorrectStep, T3.CorrectStep, T2.CorrectStep.
  assert (Hc2 : T2.Correct s2)
    by now unfold Correct, T5.Correct, T4.Correct, T3.Correct in Hc; tauto.
  assert (L1 : T2.NonDecreasingScore s2 s2') by now apply (T2P.StepNonDecreasingScore s2 s2').
  assert (L2 : T2.NonDecreasingLevel s2 s2') by now apply (T2P.StepNonDecreasingLevel s2' Hc2).
  assert (L3 : T2.ScoreRisesOnClear s2 s2') by now apply (T2P.StepScoreRisesOnClear s2 s2').
  assert (L4 : T3.HoldMonotone s3 s3') by now apply (T3P.StepHoldMonotone s3 s3').
  split_top; auto using L1, L2, L3, L4.
Qed.


