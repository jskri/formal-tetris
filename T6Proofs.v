Lemma RotateKickNotGameover : ∀ [s s' cw]
  (H1 : RotateKickPiece cw s = Some s'),
  gameover s = false.
Proof.
  intros.
  unfold RotateKickPiece in H1; cbv zeta in H1.
  destruct (! gameover s &&
    ! match T5.RotatePiece cw s with Some _ => true | None => false end) eqn: E.
  - apply andb_true_iff in E as [E1 _]; now apply negb_true_iff in E1.
  - unfold gameover in E; rewrite E in H1; discriminate H1.
Qed.