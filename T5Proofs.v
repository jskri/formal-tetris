(* Structural fact about ShadowYImpl: no hypothesis on Valid at the starting
position needed (this is a pure fact about the recursive definition). Either
the fuel-based search reaches a genuine stop (Valid fails one row further
down), or it consumes exactly the given fuel without ever finding one. *)
Lemma ShadowYImplStopsOrExhausts : ∀ (fuel : ℕ) (g : Grid) (pc : Piece) (y0 x0 pr0 : ℤ),
    Valid g pc (ShadowYImpl fuel g pc y0 x0 pr0 - 1, x0) pr0 = false
  ∨ ShadowYImpl fuel g pc y0 x0 pr0 = y0 - Z.of_nat fuel.
Proof.
  induction fuel as [| fuel' IH]; intros g pc y0 x0 pr0; simpl.
  - right; lia.
  - destruct (Valid g pc (y0 - 1, x0) pr0) eqn: Hstep; simpl.
    + destruct (IH g pc (y0 - 1) x0 pr0) as [IH1 | IH2].
      * left; exact IH1.
      * right; rewrite IH2; lia.
    + left; exact Hstep.
Qed.

(* ShadowY always finds a position it genuinely cannot descend from one more
row (regardless of whether the piece was itself Valid at py, i.e.
regardless of gameover). Only TypeOK-level facts are needed (always available
from CorrectWithoutGameover): if fuel runs out before a genuine stop,
ShadowYFuelSufficient says the search passed the floor 1-PW, and
ValidBelowFloor (itself HV0-free) forces invalidity there too. *)
Lemma ShadowYAlwaysStops : ∀ (s4 : T4.State)
  (Hc4 : T4.CorrectWithoutGameover s4),
  Valid (T4.mg s4) (T4.p s4) (ShadowY s4 - 1, T4.px s4) (T4.pr s4) = false.
Proof.
  intros s4 Hc4.
  assert (Hc3 : T3.CorrectWithoutGameover (T4.s3 s4)) by now destruct Hc4; tauto.
  assert (Hc2 : T2.CorrectWithoutGameover (T3.s2 (T4.s3 s4))) by now destruct Hc3; tauto.
  assert (Hc1 : T1.CorrectWithoutGameover (T2.s1 (T3.s2 (T4.s3 s4)))) by now destruct Hc2; tauto.
  assert (HTY : T1.Y (T4.mg s4) = 0). {
    assert (HT1 : T1.TypeOK (T2.s1 (T3.s2 (T4.s3 s4)))) by now destruct Hc1; tauto.
    assert (EYX1 : T1.YX (T1.mg (T2.s1 (T3.s2 (T4.s3 s4)))) = T1.YX T1.InitialMainGrid)
      by now apply T1P.TypeOKSpec2 in HT1; tauto.
    assert (EYX0 : T1.YX T1.InitialMainGrid = (0, 0))
      by now pose proof T1.AxiomsInitialMainGrid; tauto.
    change (T4.mg s4) with (T1.mg (T2.s1 (T3.s2 (T4.s3 s4)))).
    unfold T1.Y; rewrite EYX1, EYX0; reflexivity.
  }
  assert (HRpr : 0 ≤ T4.pr s4 < 4). {
    assert (HT1 : T1.TypeOK (T2.s1 (T3.s2 (T4.s3 s4)))) by now destruct Hc1; tauto.
    assert (HPR : 0 <= T1.pr (T2.s1 (T3.s2 (T4.s3 s4))) <= 3)
      by now apply T1P.TypeOKSpec2 in HT1; tauto.
    keep_only HPR; unfold T4.pr; lia.
  }
  unfold ShadowY.
  destruct (ShadowYImplStopsOrExhausts (Z.to_nat (T4.py s4) + Z.to_nat PW - 1)
              (T4.mg s4) (T4.p s4) (T4.py s4) (T4.px s4) (T4.pr s4)) as [H | H].
  - exact H.
  - apply T1P.ValidBelowFloor; [exact HTY | exact HRpr | ].
    pose proof (ShadowYFuelSufficient (T4.py s4)) as Hle; lia.
Qed.

(* A stopped search is a no-op when restarted from its own result. *)
Lemma ShadowYImplNoOpWhenStopped : ∀ (fuel : ℕ) (g : Grid) (pc : Piece) (y x pr : ℤ),
  Valid g pc (y - 1, x) pr = false →
  ShadowYImpl fuel g pc y x pr = y.
Proof.
  intros fuel g pc y x pr H; destruct fuel as [| fuel']; simpl; [reflexivity |].
  rewrite H; reflexivity.
Qed.

(* ShadowY is idempotent: recomputing it from a state whose py is already
ShadowY s4 (and whose mg/p/pr/px agree with s4) gives back the same value.
No gameover hypothesis needed on either state. *)
Lemma ShadowYIdempotent : ∀ (s4 s4' : T4.State)
  (Hc4 : T4.CorrectWithoutGameover s4)
  (Emg : T4.mg s4' = T4.mg s4)
  (Ep  : T4.p  s4' = T4.p  s4)
  (Epr : T4.pr s4' = T4.pr s4)
  (Epx : T4.px s4' = T4.px s4)
  (Epy : T4.py s4' = ShadowY s4),
  ShadowY s4' = ShadowY s4.
Proof.
  intros s4 s4' Hc4 Emg Ep Epr Epx Epy.
  assert (Hstop := ShadowYAlwaysStops s4 Hc4).
  unfold ShadowY at 1.
  rewrite Emg, Ep, Epr, Epx, Epy.
  apply ShadowYImplNoOpWhenStopped; exact Hstop.
Qed.

Lemma ShadowYImplValidOrNoMove : ∀ (fuel : ℕ) (g : Grid) (pc : Piece) (y0 x0 pr0 : ℤ),
  ShadowYImpl fuel g pc y0 x0 pr0 = y0
  ∨ Valid g pc (ShadowYImpl fuel g pc y0 x0 pr0, x0) pr0 = true.
Proof.
  induction fuel as [| fuel' IH]; intros g pc y0 x0 pr0; simpl.
  - left; reflexivity.
  - destruct (Valid g pc (y0 - 1, x0) pr0) eqn: Hstep; simpl.
    + right.
      destruct (IH g pc (y0 - 1) x0 pr0) as [IH1 | IH2].
      * rewrite IH1; exact Hstep.
      * exact IH2.
    + left; reflexivity.
Qed.

Lemma ShadowYValidOrNoMove : ∀ (s4 : T4.State),
  ShadowY s4 = T4.py s4
  ∨ Valid (T4.mg s4) (T4.p s4) (ShadowY s4, T4.px s4) (T4.pr s4) = true.
Proof.
  intro s4; unfold ShadowY; apply ShadowYImplValidOrNoMove.
Qed.

(* T4-level version, same telescoping technique as FixPieceFreshPieceT4: chase
T1Proofs.FixPieceOK's gameover-accuracy conjunct (its 5th) up to the T4.FixPiece
result instead of extracting the fresh-piece facts (its 2nd-4th). *)
Lemma FixPieceGameoverEqT4 : ∀ [bagNew] [H : T4.PieceSet bagNew]
  [s4'' s4Result : T4.State]
  (Hn : T4.FixPiece bagNew H s4'' = Some s4Result),
  T1.gameover (T2.s1 (T3.s2 (T4.s3 s4Result)))
  = (ForbiddenGrid ∩ T1.mg (T2.s1 (T3.s2 (T4.s3 s4Result))) ⊈ ∅).
Proof.
  intros.
  assert (Hn3 : T3.FixPiece (T4.next s4'' 0) (T4.s3 s4'') = Some (T4.s3 s4Result))
    by (apply T4P.FixPieceStep in Hn as [E _]; exact E).
  assert (Hn2 : T2.FixPiece (T4.next s4'' 0) (T3.s2 (T4.s3 s4''))
              = Some (T3.s2 (T4.s3 s4Result)))
    by (apply T3P.FixPieceStep in Hn3 as [E _]; exact E).
  unfold T2.FixPiece in Hn2; cbv zeta in Hn2.
  destruct (OptionMapSome Hn2) as [s1Result [Hn1 Es1]].
  destruct (T1P.FixPieceOK (T4.next s4'' 0) (T2.s1 (T3.s2 (T4.s3 s4''))) s1Result Hn1)
    as (_ & _ & _ & _ & Ego).
  assert (Es1' : T2.s1 (T3.s2 (T4.s3 s4Result)) = s1Result)
    by (rewrite <- Es1; reflexivity).
  rewrite Es1'; exact Ego.
Qed.

(* T5-level wrapper: FixPiece = option_map (UpdateShadowY s) (T4.FixPiece ...),
so this transfers straight through FixPieceStep. Since T6.FixPiece/gameover/mg
are transparent aliases of T5's, this is usable at the T6 level as-is. *)
Lemma FixPieceGameoverEq : ∀ [bagNew] [H : T4.PieceSet bagNew] [s s' : State]
  (Hn : FixPiece bagNew H s = Some s'),
  gameover s' = (ForbiddenGrid ∩ mg s' ⊈ ∅).
Proof.
  intros.
  destruct (FixPieceStep Hn) as (s4' & E4 & Es4 & _).
  assert (Ego := FixPieceGameoverEqT4 E4).
  assert (Emg : mg s' = T1.mg (T2.s1 (T3.s2 (T4.s3 s4'))))
    by (unfold mg; rewrite Es4; reflexivity).
  assert (Egameover : gameover s' = T1.gameover (T2.s1 (T3.s2 (T4.s3 s4'))))
    by (unfold gameover; rewrite Es4; reflexivity).
  rewrite Egameover, Emg; exact Ego.
Qed.

(* T6.FixPiece always resets `swapped` to false, unconditionally. Needed
because NewMainGridGameoverState changes `gameover` but not `swapped`, so
GameoverImplyNotSwapped for the materialized state can't lean on s6''s own
invariant (whose antecedent is the *old*, single-player gameover flag, not
the multiplayer one). *)
Lemma FixPieceSwappedFalse : ∀ [bagNew] [H : T4.PieceSet bagNew] [s s' : State]
  (Hn : FixPiece bagNew H s = Some s'),
  T3.swapped (T4.s3 (s4 s')) = false.
Proof.
  intros.
  destruct (FixPieceStep Hn) as (s4' & E4 & Es4 & _).
  destruct (T4P.FixPieceStep E4) as (E3 & _).
  destruct (T3P.FixPieceStep E3) as (_ & _ & Esw).
  rewrite Es4; exact Esw.
Qed.