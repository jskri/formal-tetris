Lemma NextRefine : ∀ e4 s5 s5'
  (H1 : GyEqShadowY s5)
  (H2 : NextT4Event e4 s5 = Some s5'),
  T4.Next (fₑ e4) (fₛ s5) = Some (fₛ s5').
