Lemma OptionMapSomeInv : ∀ [A B : Type] (f : A → B) (o : option A) (b : B)
  (H : option_map f o = Some b),
  ∃ a, o = Some a.
Proof.
  intros; destruct o as [a |].
  - exists a; reflexivity.
  - discriminate H.
Qed.

Lemma OptionMapSome : ∀ [A B : Type] [f : A → B] [optA : option A] [b : B]
  (H1 : option_map f optA = Some b),
  ∃ a, optA = Some a ∧ f a = b.
Proof.
  intros.
  destruct optA as [a |].
  - Check (H1 : option_map f (Some a) = Some b).
    exists a.
    simpl in H1; inject H1; tauto.
  - Check (H1 : option_map f None = Some b).
    simpl in H1; discriminate H1.
Qed.

(* Every T4-forwarded T5 event has the shape
 * `option_map (UpdateShadowY s) (optS4)`; this is the unique place where shape
 * is unfolded. *)
Lemma UpdateShadowYStep : ∀ [s s' : State] [optS4 : option T4.State]
  (Hn : option_map (UpdateShadowY s) optS4 = Some s'),
  ∃ s4', optS4 = Some s4' ∧ s4 s' = s4' ∧ gy s' = ShadowY s4'.
Proof.
  intros.
  destruct optS4 as [s4' |] eqn: E.
  - exists s4'; split; [ reflexivity | ].
    cbv beta iota in Hn.
    assert (L1 : s' = UpdateShadowY s s4') by (inject Hn; now symmetry).
    rewrite L1; unfold UpdateShadowY; split; reflexivity.
  - discriminate Hn.
Qed.


