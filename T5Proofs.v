(* T2.FixPiece forwards to T1.FixPiece under an option_map wrapper (score/level
 * bookkeeping only); its success therefore implies T1.FixPiece's does too, and
 * T1.FixPiece's own guard forces gameover=false. *)
Lemma FixPieceGuardGameover : ∀ [bagNew] [H : T4.PieceSet bagNew]
  [s4'' s4Result : T4.State]
  (Hn : T4.FixPiece bagNew H s4'' = Some s4Result),
  T4.gameover s4'' = false.
Proof.
  intros.
  assert (Hn3 : T3.FixPiece (T4.next s4'' 0) (T4.s3 s4'') = Some (T4.s3 s4Result))
    by (apply T4P.FixPieceStep in Hn as [E _]; exact E).
  assert (Hn2 : T2.FixPiece (T4.next s4'' 0) (T3.s2 (T4.s3 s4''))
              = Some (T3.s2 (T4.s3 s4Result)))
    by (apply T3P.FixPieceStep in Hn3 as [E _]; exact E).
  unfold T2.FixPiece in Hn2; cbv zeta in Hn2.
  apply OptionMapSomeInv in Hn2 as [s1Result Hn1].
  unfold T1.FixPiece in Hn1.
  destruct (! T1.gameover (T2.s1 (T3.s2 (T4.s3 s4''))) &&
            ! T1.CanMovePiece (-1, 0)%Z (T2.s1 (T3.s2 (T4.s3 s4'')))) eqn: Eg;
    [ | discriminate Hn1 ].
  apply andb_true_iff in Eg as [Eg1 _]; apply negb_true_iff in Eg1.
  unfold T4.gameover; exact Eg1.
Qed.

(* Same chain as FixPieceGuardGameover, but extracting the fresh-spawn facts
(p/pyx/pr) about the *output* state instead of the gameover guard on the
input. Needs OptionMapSome (not OptionMapSomeInv) since, unlike
FixPieceGuardGameover, this has to relate the witness s1Result back to the
actual output state's own s1 projection. *)
Lemma FixPieceFreshPieceT4 : ∀ [bagNew] [H : T4.PieceSet bagNew]
  [s4'' s4Result : T4.State]
  (Hn : T4.FixPiece bagNew H s4'' = Some s4Result),
  ∃ pNew,
    T1.p (T2.s1 (T3.s2 (T4.s3 s4Result))) = pNew
  ∧ T1.pyx (T2.s1 (T3.s2 (T4.s3 s4Result))) = T1.InitialYX pNew
  ∧ T1.pr (T2.s1 (T3.s2 (T4.s3 s4Result))) = 0.
Proof.
  intros.
  assert (Hn3 : T3.FixPiece (T4.next s4'' 0) (T4.s3 s4'') = Some (T4.s3 s4Result))
    by (apply T4P.FixPieceStep in Hn as [E _]; exact E).
  assert (Hn2 : T2.FixPiece (T4.next s4'' 0) (T3.s2 (T4.s3 s4''))
              = Some (T3.s2 (T4.s3 s4Result)))
    by (apply T3P.FixPieceStep in Hn3 as [E _]; exact E).
  unfold T2.FixPiece in Hn2; cbv zeta in Hn2.
  destruct (OptionMapSome Hn2) as [s1Result [Hn1 Es1]].
  exists (T4.next s4'' 0).
  destruct (T1P.FixPieceOK (T4.next s4'' 0) (T2.s1 (T3.s2 (T4.s3 s4''))) s1Result Hn1)
    as (_ & Ep & Epyx & Epr & _).
  assert (Es1' : T2.s1 (T3.s2 (T4.s3 s4Result)) = s1Result)
    by (rewrite <- Es1; reflexivity).
  rewrite Es1'.
  split; [exact Ep | split; [exact Epyx | exact Epr]].
Qed.

Lemma FixPieceFreshPiece : ∀ [s s' bagNew] [H : T4.PieceSet bagNew]
  (Hn : FixPiece bagNew H s = Some s'),
  ∃ pNew,
    T1.p (T2.s1 (T3.s2 (T4.s3 (s4 s')))) = pNew
  ∧ T1.pyx (T2.s1 (T3.s2 (T4.s3 (s4 s')))) = T1.InitialYX pNew
  ∧ T1.pr (T2.s1 (T3.s2 (T4.s3 (s4 s')))) = 0.
Proof.
  intros.
  destruct (FixPieceStep Hn) as (s4' & E4 & Es4 & _).
  rewrite Es4.
  exact (FixPieceFreshPieceT4 E4).
Qed.


