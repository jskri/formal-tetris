(* ShadowYImpl only ever descends while Valid holds one step lower, and stops
 * the instant it doesn't. Stated on `i`-style fuel/position pairs, mirroring
 * T1Proofs' FilterFullLinesSpec: as long as fuel is large enough to reach the
 * floor 1-PW (ValidBelowFloor, T1Proofs.v), the search cannot run out of fuel
 * before it runs out of room to fall. Every conclusion below is therefore
 * unconditional on the value of fuel, only on it being large enough. *)
Lemma ShadowYImplSpec : ∀ (fuel : ℕ) (g : Grid) (pc : Piece) (y0 x0 pr0 : ℤ)
  (HTY : T1.Y g = 0)
  (HR : 0 ≤ pr0 < 4)
  (HV0 : Valid g pc (y0, x0) pr0 = true)
  (HF : y0 - Z.of_nat fuel ≤ 1 - PW),
  let y' := ShadowYImpl fuel g pc y0 x0 pr0 in
    y' ≤ y0
  ∧ Valid g pc (y', x0) pr0 = true
  ∧ Valid g pc (y' - 1, x0) pr0 = false
  ∧ (∀ y, y' < y ≤ y0 → Valid g pc (y, x0) pr0 = true).
Proof.
  induction fuel as [| fuel' IH]; intros g pc y0 x0 pr0 HTY HR HV0 HF; cbv zeta.
  - (* No fuel left: HF (at fuel=0) gives y0 ≤ 1-PW, and HV0 via the
     * contrapositive of ValidBelowFloor gives y0 ≥ 1-PW, so y0 = 1-PW exactly
     * and one step down is unconditionally invalid. *)
    assert (Hge : 1 - PW ≤ y0). {
      destruct (Z_lt_le_dec y0 (1 - PW)) as [Hlt | Hle]; [ | exact Hle ].
      exfalso; assert (Hc := T1P.ValidBelowFloor g pc y0 x0 pr0 HTY HR Hlt).
      rewrite Hc in HV0; discriminate HV0.
    }
    assert (Heq : y0 = 1 - PW). {
      keep_only HF Hge.
      change (Z.of_nat 0) with 0%Z in HF.
      lia.
    }
    assert (HV1 : Valid g pc (y0 - 1, x0) pr0 = false). {
      apply T1P.ValidBelowFloor; (exact HTY || exact HR || keep_only Heq; lia).
    }
    enough (y0 <= y0
          ∧ Valid g pc (y0, x0) pr0 = true
          ∧ Valid g pc (y0 - 1, x0) pr0 = false
          ∧ ∀ y : ℤ, y0 < y <= y0 → Valid g pc (y, x0) pr0 = true)
      by now cbn [ShadowYImpl].
    repeat split; try assumption; try (intros y Hy; exfalso; keep_only Hy); lia.
  - (* One unit of fuel: test one step down. *)
    destruct (Valid g pc (y0 - 1, x0) pr0) eqn: Hstep.
    + (* still valid one step down: recurse *)
      assert (Eeq : ShadowYImpl (S fuel') g pc y0 x0 pr0
                  = ShadowYImpl fuel' g pc (y0 - 1) x0 pr0). {
        cbn [ShadowYImpl]; rewrite Hstep; reflexivity.
      }
      assert (HF' : (y0 - 1) - Z.of_nat fuel' ≤ 1 - PW)
        by (keep_only HF; rewrite Nat2Z.inj_succ in HF; lia).
      set (I := IH g pc (y0 - 1) x0 pr0 HTY HR Hstep HF').
      assert (Hle : ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 <= y0 - 1)
        by now destruct I; tauto.
      assert (HVy' : Valid g pc (ShadowYImpl fuel' g pc (y0 - 1) x0 pr0, x0) pr0 = true)
        by now destruct I; tauto.
      assert (HVy'1 : Valid g pc (ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 - 1, x0) pr0 = false)
        by now destruct I; tauto.
      assert (Hall : ∀ y : ℤ, ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 < y <= y0 - 1 → Valid g pc (y, x0) pr0 = true)
        by now destruct I; tauto.
      cbv zeta in Hle, HVy', HVy'1, Hall.
      enough (
          ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 <= y0
        ∧ Valid g pc (ShadowYImpl fuel' g pc (y0 - 1) x0 pr0, x0) pr0 = true
        ∧ Valid g pc (ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 - 1, x0) pr0 = false
        ∧ ∀ y : ℤ, ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 < y <= y0 → Valid g pc (y, x0) pr0 = true)
        by now rewrite Eeq.
      assert (L1 : ∀ y : ℤ, ShadowYImpl fuel' g pc (y0 - 1) x0 pr0 < y <= y0
          → Valid g pc (y, x0) pr0 = true). {
        intros y Hy.
        destruct (Z.eq_dec y y0) as [Ey | Ey].
        - rewrite Ey; exact HV0.
        - apply Hall; keep_only Hy Ey; lia.
      }
      repeat split; (lia || exact HVy' || exact HVy'1 || apply L1).
    + (* not valid one step down: stop here *)
      assert (Eeq : ShadowYImpl (S fuel') g pc y0 x0 pr0 = y0). {
        cbn [ShadowYImpl]; rewrite Hstep; reflexivity.
      }
      enough (
          y0 <= y0
        ∧ Valid g pc (y0, x0) pr0 = true
        ∧ Valid g pc (y0 - 1, x0) pr0 = false
        ∧ ∀ y : ℤ, y0 < y <= y0 → Valid g pc (y, x0) pr0 = true)
        by now rewrite Eeq.
      repeat split; (lia || exact HV0 || exact Hstep ||
        (intros y Hy; exfalso; keep_only Hy; lia)).
Qed.

(* fuel = (Z.to_nat py) + (Z.to_nat PW) - 1 is always large enough to reach the
 * floor 1-PW: y0 - fuel ≤ 1-PW. When py ≥ 0 the fuel equals py+PW-1 exactly, so
 * y0-fuel = 1-PW (tight). When py < 0, Z.to_nat clamps py to 0, giving fuel
 * PW-1; then y0 - (PW-1) = py + 1 - PW ≤ 1 - PW since py < 0 (over-provisioned,
 * the search simply stops earlier when Valid fails). *)
Lemma ShadowYFuelSufficient : ∀ (py0 : ℤ),
  py0 - Z.of_nat (Z.to_nat py0 + Z.to_nat PW - 1) ≤ 1 - PW.
Proof.
  intro py0.
  assert (HPWpos : PW > 0) by (apply T1.AxiomsPW).
  assert (HPWnat : (1 <= Z.to_nat PW)%nat) by lia.
  destruct (Z_le_gt_dec 0 py0) as [Hpos | Hneg].
  - (* py0 ≥ 0: fuel = py0 + PW - 1 exactly, so y0 - fuel = 1 - PW. *)
    assert (Epy : Z.of_nat (Z.to_nat py0) = py0) by lia.
    assert (EPW : Z.of_nat (Z.to_nat PW) = PW) by lia.
    assert (Esub : Z.of_nat (Z.to_nat py0 + Z.to_nat PW - 1)
                 = Z.of_nat (Z.to_nat py0 + Z.to_nat PW) - 1)
      by (apply Nat2Z.inj_sub; lia).
    assert (Eadd : Z.of_nat (Z.to_nat py0 + Z.to_nat PW)
                 = Z.of_nat (Z.to_nat py0) + Z.of_nat (Z.to_nat PW))
      by (apply Nat2Z.inj_add).
    rewrite Esub, Eadd, Epy, EPW; lia.
  - (* py0 < 0: fuel = PW - 1, and py0 - (PW-1) ≤ 1 - PW because py0 ≤ 0. *)
    assert (Ezero : Z.to_nat py0 = 0%nat) by lia.
    assert (Efuel : Z.of_nat (Z.to_nat py0 + Z.to_nat PW - 1) = PW - 1). {
      rewrite Ezero, Nat.add_0_l.
      assert (E1 : Z.of_nat (Z.to_nat PW - 1) = Z.of_nat (Z.to_nat PW) - 1)
        by (apply Nat2Z.inj_sub; lia).
      assert (EPW : Z.of_nat (Z.to_nat PW) = PW) by lia.
      rewrite E1, EPW; reflexivity.
    }
    rewrite Efuel; keep_only Hneg; lia.
Qed.


