  assert (Hc4 : T4.Correct (s4 s)) by now unfold Correct in Hc; tauto.
  (* Relocate to the shadow position, which is Valid by LowestShadowY,
    * provided the game is not already over; then FixPiece succeeding forces
    * exactly that (its own guard requires ¬gameover). *)
  destruct (DropPieceStep Hm) as (s4Res & E4 & Es4 & Egy).
  assert (Hgos : T4.gameover (s4 (NewPieceYXState (gy s, px s) s)) = false)
    by (apply (FixPieceGuardGameover E4)).
