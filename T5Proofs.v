(* The piece is Valid at its own current position (mg,p,pyx,pr), whenever the
 * game is not over: PieceOccupiedInsideBounds holds unconditionally,
 * PieceOnFreeBlocks under `¬gameover`, and Valid is exactly their conjunction. *)
Lemma T1PieceValidNow : ∀ (s1 : T1.State)
  (Hc1 : T1.Correct s1)
  (Hgo1 : T1.gameover s1 = false),
  Valid (T1.mg s1) (T1.p s1) (T1.pyx s1) (T1.pr s1) = true.
Proof.
  intros s1 Hc1 Hgo1.
  assert (Hoib : T1.PieceOccupiedInsideBounds s1) by now apply T1P.CorrectSpec in Hc1; tauto.
  assert (Hofb : T1.PieceOnFreeBlocks s1) by now apply T1P.CorrectSpec in Hc1; tauto.
  unfold T1.PieceOccupiedInsideBounds in Hoib.
  unfold T1.PieceOnFreeBlocks in Hofb; specialize (Hofb Hgo1).
  unfold Valid; apply andb_true_iff; split; (exact Hoib || exact Hofb).
Qed.

Lemma ShadowYSpec : ∀ (s4' : T4.State)
  (Hc4 : T4.Correct s4')
  (Hgo : T4.gameover s4' = false),
    ShadowY s4' ≤ T4.py s4'
  ∧ Valid (T4.mg s4') (T4.p s4') (ShadowY s4', T4.px s4') (T4.pr s4') = true
  ∧ Valid (T4.mg s4') (T4.p s4') (ShadowY s4' - 1, T4.px s4') (T4.pr s4') = false
  ∧ (∀ y, y ≤ T4.py s4' →
      Valid (T4.mg s4') (T4.p s4') (y, T4.px s4') (T4.pr s4') = true →
      Valid (T4.mg s4') (T4.p s4') (y - 1, T4.px s4') (T4.pr s4') = false →
      y ≤ ShadowY s4').
Proof.
  intros s4' Hc4 Hgo.
  assert (Hc3 : T3.Correct (T4.s3 s4')) by now destruct Hc4; tauto.
  assert (Hc2 : T2.Correct (T3.s2 (T4.s3 s4'))) by now destruct Hc3; tauto.
  assert (Hc1 : T1.Correct (T2.s1 (T3.s2 (T4.s3 s4')))) by now destruct Hc2; tauto.
  (* mg/p/py/px/pr/gameover at T4 are, by definition, the corresponding T1
   * projections of the same underlying T1 state. *)
  assert (Emg : T4.mg s4' = T1.mg (T2.s1 (T3.s2 (T4.s3 s4')))) by reflexivity.
  assert (Ep : T4.p s4' = T1.p (T2.s1 (T3.s2 (T4.s3 s4')))) by reflexivity.
  assert (Epy : T4.py s4' = T1.py (T2.s1 (T3.s2 (T4.s3 s4')))) by reflexivity.
  assert (Epx : T4.px s4' = T1.px (T2.s1 (T3.s2 (T4.s3 s4')))) by reflexivity.
  assert (Epr : T4.pr s4' = T1.pr (T2.s1 (T3.s2 (T4.s3 s4')))) by reflexivity.
  assert (Ego : T4.gameover s4' = T1.gameover (T2.s1 (T3.s2 (T4.s3 s4')))) by reflexivity.
  rewrite Ego in Hgo.
  assert (Epyx : T1.pyx (T2.s1 (T3.s2 (T4.s3 s4')))
               = (T4.py s4', T4.px s4')). {
    rewrite Epy, Epx; unfold T1.py, T1.px; apply surjective_pairing.
  }
  assert (HV0 : Valid (T4.mg s4') (T4.p s4') (T4.py s4', T4.px s4') (T4.pr s4') = true). {
    rewrite Emg, Ep, Epr; rewrite <- Epyx.
    apply T1PieceValidNow; [ exact Hc1 | exact Hgo ].
  }
  assert (HTY : T1.Y (T4.mg s4') = 0). {
    assert (HT1 : T1.TypeOK (T2.s1 (T3.s2 (T4.s3 s4'))))
      by now apply T1P.CorrectSpec in Hc1; tauto.
    assert (EYX1 : T1.YX (T1.mg (T2.s1 (T3.s2 (T4.s3 s4')))) = T1.YX T1.InitialMainGrid)
      by now apply T1P.TypeOKSpec2 in HT1; tauto.
    assert (EYX0 : T1.YX T1.InitialMainGrid = (0, 0))
      by now pose proof T1.AxiomsInitialMainGrid; tauto.
    rewrite Emg; unfold T1.Y; rewrite EYX1, EYX0; reflexivity.
  }
  assert (HRpr : 0 ≤ T4.pr s4' < 4). {
    assert (HT1 : T1.TypeOK (T2.s1 (T3.s2 (T4.s3 s4'))))
      by now apply T1P.CorrectSpec in Hc1; tauto.
    assert (HPR : 0 <= T1.pr (T2.s1 (T3.s2 (T4.s3 s4'))) <= 3)
      by now apply T1P.TypeOKSpec2 in HT1; tauto.
    rewrite Epr; keep_only HPR; lia.
  }
  unfold ShadowY.
  assert (HF := ShadowYFuelSufficient (T4.py s4')).
  destruct (ShadowYImplSpec (Z.to_nat (T4.py s4') + Z.to_nat PW - 1)
              (T4.mg s4') (T4.p s4') (T4.py s4') (T4.px s4') (T4.pr s4')
              HTY HRpr HV0 HF)
    as (Hle & HVy' & HVy'1 & Hall).
  cbv zeta in Hle, HVy', HVy'1, Hall.
  repeat split.
  - exact Hle.
  - exact HVy'.
  - exact HVy'1.
  - intros y Hy1 Hy2 Hy3.
    destruct (Z_le_gt_dec y (ShadowYImpl (Z.to_nat (T4.py s4') + Z.to_nat PW - 1)
                              (T4.mg s4') (T4.p s4') (T4.py s4') (T4.px s4') (T4.pr s4')))
      as [Hok | Hbad]; [ exact Hok | ].
    (* if y were strictly above the computed shadow, the spec says Valid(y-1)
     * would hold there — contradicting Hy3. *)
    exfalso.
    set (y' := ShadowYImpl (Z.to_nat (T4.py s4') + Z.to_nat PW - 1)
                 (T4.mg s4') (T4.p s4') (T4.py s4') (T4.px s4') (T4.pr s4')) in *.
    assert (Hrange : y' < y ≤ T4.py s4') by (keep_only Hbad Hy1; lia).
    destruct (Z.eq_dec (y - 1) y') as [Eeq | Eneq].
    + rewrite Eeq in Hy3; rewrite HVy' in Hy3; discriminate Hy3.
    + assert (Hin : y' < y - 1 ≤ T4.py s4') by (keep_only Hrange Eneq; lia).
      assert (Hv := Hall (y - 1) Hin); rewrite Hv in Hy3; discriminate Hy3.
Qed.

