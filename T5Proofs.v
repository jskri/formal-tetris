    by reflexivity.
  rewrite Egogo in Hgos.
  (* From LowestShadowY s and ¬gameover s, the shadow position is Valid. *)
  assert (Hgos5 : gameover s = false) by (unfold gameover; exact Hgos).
  assert (HLow : LowestShadowY s) by now unfold Correct in Hc; tauto.
  unfold LowestShadowY in HLow; specialize (HLow Hgos5).
  assert (HVgy : ValidPieceCannotGoDown s (gy s))
    by now destruct HLow; tauto.
  unfold ValidPieceCannotGoDown in HVgy; destruct HVgy as [HVgy _].
  (* HVgy : Valid (mg s) (p s) (gy s, px s) (pr s) = true, where mg/p/px/pr are
    * the T5 projections, all equal by definition to the T1 ones. *)
  (* Reconstruct T4.Correct of the relocated state from T1's relocation lemma. *)
  assert (Hc1' : T1.Correct
            (T1.NewPieceYXState (gy s, px s) (T2.s1 (T3.s2 (T4.s3 (s4 s)))))). {
    apply T1P.NewPieceYXStateCorrect.
    - assert (Hc3 : T3.Correct (T4.s3 (s4 s))) by now destruct Hc4; tauto.
      assert (Hc2 : T2.Correct (T3.s2 (T4.s3 (s4 s)))) by now destruct Hc3; tauto.
      assert (Hc1 : T1.Correct (T2.s1 (T3.s2 (T4.s3 (s4 s))))) by now destruct Hc2; tauto.
      exact Hc1.
    - unfold mg, p, pr, px in HVgy.
      unfold T4.mg, T4.p, T4.pr, T4.px in HVgy.
      exact HVgy.
  }
  assert (Hc4'' : T4.Correct (s4 (NewPieceYXState (gy s, px s) s))). {
    (* Level/hold/swapped/Draw are all literally unchanged by the relocation,
      * at every intermediate layer. *)
    assert (Hc3 : T3.Correct (T4.s3 (s4 s))) by now destruct Hc4; tauto.
    assert (HCD : T4.CorrectD (T4.d (s4 s))) by now destruct Hc4; tauto.
    assert (Hc2 : T2.Correct (T3.s2 (T4.s3 (s4 s)))) by now destruct Hc3; tauto.
    assert (HSw : T3.SwappedImplyHoldSome (T4.s3 (s4 s))) by now destruct Hc3; tauto.
    assert (HGoNS : T3.GameoverImplyNotSwapped (T4.s3 (s4 s))) by now destruct Hc3; tauto.
    assert (HLv : T2.LevelCorrect (T3.s2 (T4.s3 (s4 s)))) by now destruct Hc2; tauto.
    unfold T4.Correct; split.
    - unfold T3.Correct; split; [ | split ];
      ((unfold T2.Correct; split; [ exact Hc1' | exact HLv ]) ||
      exact HSw || exact HGoNS).
    - exact HCD.
  }
  (* T4.FixPiece succeeding on this relocated, Correct state preserves T4.Correct.
    * T4.Next (T4.Fix bagNew H) s'' is convertible to T4.FixPiece bagNew H s''. *)
  assert (E4' : T4.Next (T4.Fix bagNew H) (s4 (NewPieceYXState (gy s, px s) s))
              = Some s4Res) by (exact E4).
  assert (Hc4Res : T4.Correct s4Res)
    by (eapply T4P.NextCorrect; (exact Hc4'' || exact E4')).
  assert (L1 : T4.Correct (s4 s'))
    by now rewrite Es4; exact Hc4Res.
  assert (L2 : LowestShadowY s'). {
    unfold LowestShadowY; intros Hgo.
    assert (Hgo' : T4.gameover s4Res = false)
      by (unfold gameover in Hgo; rewrite Es4 in Hgo; exact Hgo).
    destruct (ShadowYSpec s4Res Hc4Res Hgo') as (H1 & H2 & H3 & H4).
    assert (Emg' : mg s' = T4.mg s4Res) by (unfold mg; rewrite Es4; reflexivity).
    assert (Ep' : p s' = T4.p s4Res) by (unfold p; rewrite Es4; reflexivity).
    assert (Epx' : px s' = T4.px s4Res) by (unfold px; rewrite Es4; reflexivity).
    assert (Epr' : pr s' = T4.pr s4Res) by (unfold pr; rewrite Es4; reflexivity).
    assert (Epy' : py s' = T4.py s4Res) by (unfold py; rewrite Es4; reflexivity).
    assert (L2_1 : ∀ y : ℤ,
        y <= T4.py s4Res
        → Valid (T4.mg s4Res) (T4.p s4Res) (y, T4.px s4Res) (T4.pr s4Res) =
        true
        ∧ Valid (T4.mg s4Res) (T4.p s4Res) (y - 1, T4.px s4Res)
        (T4.pr s4Res) = false → y <= ShadowY s4Res). {
      assert (L2_1_1 :
        ∀ y : ℤ, y <= T4.py s4Res
        → Valid (T4.mg s4Res) (T4.p s4Res) (y, T4.px s4Res) (T4.pr s4Res) = true
        → Valid (T4.mg s4Res) (T4.p s4Res) (y - 1, T4.px s4Res)
          (T4.pr s4Res) = false → y <= ShadowY s4Res)
          by now destruct (ShadowYSpec s4Res Hc4Res Hgo'); tauto.
      intros y Hy1 [Hy2 Hy3]; apply (H4 y Hy1 Hy2 Hy3).
    }
    unfold ValidPieceCannotGoDown.
    rewrite Egy, Emg', Ep', Epx', Epr', Epy'.
    repeat split; ((destruct (ShadowYSpec s4Res Hc4Res Hgo'); tauto) ||
      apply L2_1).
  }
  assert (L3 : GyEqShadowY s'). {
    assert (L3_1 : gy s = ShadowY (s4 s)) by now unfold Correct, GyEqShadowY in Hc; tauto.
    apply (NextT4EventUnchangedGy L3_1 Hm).
  }
  keep_only L1 L2 L3; unfold Correct; split_top; auto using L1, L2, L3.
Qed.

Lemma NextCorrect : ∀ [e : Event] [s s' : State]
  (Hc : Correct s)
  (Hn : Next e s = Some s'),
  Correct s'.
Proof.
  intros; destruct e; eauto using NextT4EventCorrect, DropPieceCorrect.
Qed.

Theorem SpecCorrect : ∀ e s s',
    (∀ bags H, Correct (Init bags H))
  ∧ (Correct s → Next e s = Some s' → Correct s').
Proof. split; eauto using InitCorrect, NextCorrect. Qed.


